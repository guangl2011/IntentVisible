import type { OverviewPayload, PluginAlert } from "../../../../lib/plugin/types";
import { HeuristicBadge, SeverityBadge } from "./badges";

/**
 * Overview page panels (design v1.4 §2.2): Today's Alert with typed
 * reasons, the Agentic Store Summary with its provenance footer, and the
 * Intent Health Score rendered as a heuristic with clickable components —
 * never a CVR or revenue promise.
 */

const REASON_LABELS: Record<PluginAlert["reason_kind"], string> = {
  first_intent_attributed_order: "Milestone",
  intent_pending_review: "Review queue",
  refund_offset_recorded: "Billing integrity",
  single_day_snapshot: "Measurement quality",
  visibility_not_measured: "Measurement gap",
};

export function AlertsPanel({ alerts }: { alerts: PluginAlert[] }) {
  if (alerts.length === 0) {
    return (
      <div className="card empty-card">
        <strong>No alerts today.</strong>
        <p className="muted">
          Nothing needs your attention: no pending reviews, no measurement gaps, no billing surprises. New
          alerts appear here the day they trigger.
        </p>
      </div>
    );
  }
  return (
    <div className="alert-list">
      {alerts.map((alert) => (
        <div key={alert.alert_id} className="card alert-card">
          <div className="intent-head">
            <strong>
              <SeverityBadge severity={alert.severity} /> {REASON_LABELS[alert.reason_kind]}
            </strong>
          </div>
          <p>{alert.reason}</p>
        </div>
      ))}
    </div>
  );
}

export function StoreSummaryPanel({ summary }: { summary: OverviewPayload["agentic_store_summary"] }) {
  return (
    <div className="card">
      <div className="intent-head">
        <h3>Agentic Store Summary</h3>
      </div>
      <p>{summary.summary_text}</p>
      <div className="stat-grid">
        <div className="stat">
          <span className="stat-value">{summary.key_numbers.active_intent_count}</span>
          <span className="muted">active intents</span>
        </div>
        <div className="stat">
          <span className="stat-value">{summary.key_numbers.persona_count}</span>
          <span className="muted">personas</span>
        </div>
        <div className="stat">
          <span className="stat-value">{summary.key_numbers.ai_referral_sessions_7d}</span>
          <span className="muted">AI-referral sessions (7d)</span>
        </div>
      </div>
      <p className="muted provenance-footer">
        Generated by {summary.provenance.generated_by} · data window {summary.provenance.data_window_start} →{" "}
        {summary.provenance.data_window_end}
      </p>
    </div>
  );
}

export function HealthScorePanel({ score }: { score: OverviewPayload["intent_health_score"] }) {
  return (
    <div className="card">
      <div className="intent-head">
        <h3>Intent Health Score</h3>
        <HeuristicBadge />
      </div>
      <p className="health-score" aria-label={`Intent health score ${score.score} of 100`}>
        {score.score}
        <span className="muted"> / 100</span>
      </p>
      <table className="table">
        <thead>
          <tr>
            <th>Component</th>
            <th>Score</th>
            <th>Basis</th>
          </tr>
        </thead>
        <tbody>
          {score.components.map((component) => (
            <tr key={component.key}>
              <td>{component.label}</td>
              <td>{component.score}</td>
              <td className="muted">{component.detail}</td>
            </tr>
          ))}
        </tbody>
      </table>
      <p className="muted">{score.note}</p>
    </div>
  );
}
