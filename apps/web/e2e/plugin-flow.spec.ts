test("commission: §2.5 filter bar, four stat cards, order table, pinned promise", async ({
  page,
}) => {
  await login(page);
  await page.goto("/plugin/commission");

  // The pinned promise line — every commission traces to an order and
  // reconciles against Shopify (§2.5, DeepLumen lesson).
  await expect(page.getByTestId("commission-promise")).toContainText(
    "Every commission traces to a specific order number and reconciles against Shopify.",
  );

  // Filter bar with export.
  const filterBar = page.getByTestId("commission-filterbar");
  await expect(filterBar).toBeVisible();
  await expect(filterBar).toContainText("Since commission started");
  await expect(filterBar.getByText("Export CSV")).toBeVisible();

  // Seed totals reconcile exactly on the stat cards (§2.5: count, channels,
  // net billed commission, refund offsets).
  await expect(page.getByText("$96.82")).toBeVisible(); // net billed
  await expect(page.getByText("−$49.90").first()).toBeVisible(); // refund offsets
  await expect(page.locator(".stat-grid .stat").first()).toContainText("3"); // attributed orders
  // Gross → offsets → net reconciles per order in the table.
  await expect(page.getByText("gross $49.90 − offsets −$49.90")).toBeVisible(); // #1002 refunded

  // The order table carries the §2.5 column set.
  const table = page.getByTestId("commission-order-table");
  for (const header of [
    "Order",
    "Order date",
    "Billed period",
    "Attribution",
    "Order total",
    "Rate",
    "Billed commission (USD)",
    "Status",
    "Details",
  ]) {
    await expect(table.locator("th", { hasText: header }).first()).toBeVisible();
  }

  // The refunded order's row nets to zero, not a destructive edit.
  const refundedRow = page.locator("tr", { hasText: "#1002" }).first();
  await expect(refundedRow).toContainText("$49.90");
  await expect(refundedRow).toContainText("−$49.90");
  await expect(refundedRow).toContainText("$0.00");
  await expect(refundedRow).toContainText("refunded");

  // The filter bar actually filters: searching an order number narrows rows.
  await page.getByLabel("Search order number").fill("#1002");
  await expect(table.locator("tbody tr")).toHaveCount(1);
});

