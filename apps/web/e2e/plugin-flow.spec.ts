test("commission: gross → refund offsets → net reconcile per order", async ({ page }) => {
  await login(page);
  await page.goto("/plugin/commission");

  // Seed totals reconcile exactly.
  await expect(page.getByText("$146.72")).toBeVisible(); // gross
  await expect(page.getByText("−$49.90").first()).toBeVisible(); // refund offsets
  await expect(page.getByText("$96.82")).toBeVisible(); // net payable

  // The refunded order's per-order row nets to zero, not a destructive edit.
  const refundedRow = page.locator("tr", { hasText: "#1002" }).first();
  await expect(refundedRow).toContainText("$49.90");
  await expect(refundedRow).toContainText("−$49.90");
  await expect(refundedRow).toContainText("$0.00");
  await expect(refundedRow).toContainText("refunded");
});

