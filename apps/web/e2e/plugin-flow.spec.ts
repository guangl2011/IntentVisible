import type { Page } from "@playwright/test";
import { expect, test } from "@playwright/test";
import { E2E_PASSCODE } from "./config-url";

/**
 * Plugin Phase I flow (local testing plan — Layer 7 + Test Dashboard
 * Design): login → the seven plugin surfaces against the deterministic
 * demo seed served by the API fixture server (playwright.config.ts boots
 * it as the second webServer). Every assertion is a red line from the
 * test plan: provenance (engine set + window) on measured values, the
 * explicit not-measured state, estimated/heuristic labels, single-day
 * snapshots never shown as steady state, and settlement withheld for
 * simulated data. Numbers are asserted against the seed's exact values
 * so any seed drift fails here, not silently in front of a merchant.
 */

async function login(page: Page): Promise<void> {
  await page.goto("/login");
  await page.getByLabel("Passcode").fill(E2E_PASSCODE);
  await page.getByRole("button", { name: "Sign in" }).click();
  await page.waitForURL("/queue");
}

test("overview: alerts with typed reasons, provenance footer, heuristic score", async ({
  page,
}) => {
  await login(page);
  // A clean browser with no stored binding auto-selects the demo shop —
  // the binding acceptance from the test dashboard design.
  await page.goto("/plugin");

  // Simulated data mode is declared on the surface, not hidden.
  await expect(page.getByText("Simulated — numbers come from LLM-simulated runs")).toBeVisible();

  // Today's Alert: at least one alert, each rendered with its typed reason.
  const alerts = page.locator(".alert-card");
  await expect(alerts.first()).toBeVisible();
  for (const reason of ["Review queue", "Measurement gap", "Measurement quality", "Billing integrity"]) {
    await expect(page.getByText(reason)).toBeVisible();
  }

  // Agentic Store Summary carries its provenance footer.
  await expect(page.getByText("5 AI-referral sessions in the last 7 days")).toBeVisible();
  await expect(page.getByText(/Generated by .* · data window/)).toBeVisible();

  // Intent Health Score is labeled heuristic — never a CVR/revenue promise.
  await expect(page.getByText("heuristic — not a conversion or revenue forecast")).toBeVisible();
  await expect(page.locator(".health-score")).toHaveText(/75/);
});

test("buyer intents: provenance labels, single-day flag, explicit not-measured", async ({
  page,
}) => {
  await login(page);
  await page.goto("/plugin/intents");

  // All four seed units render, grouped with persona × stage.
  await expect(page.getByRole("link", { name: "S2000 vs rival power stations" })).toBeVisible();
  await expect(page.getByRole("link", { name: "How long the S2000 runs a 12V fridge" })).toBeVisible();
  await expect(page.getByRole("link", { name: "Solar panel sizing for S2000" })).toBeVisible();

  // Rolling measurement shows engines + window.
  await expect(
    page.getByText("41.2% · chatgpt.com, perplexity · 2026-11-16 → 2026-11-22 · rolling"),
  ).toBeVisible();

  // The single-day unit is labeled as a snapshot, never steady state.
  await expect(
    page.getByText("12.8% · chatgpt.com · 2026-11-22 → 2026-11-22 · single-day snapshot"),
  ).toBeVisible();

  // The not-measured unit shows the explicit state — never an invented volume.
  await expect(page.getByText("not measured")).toBeVisible();

  // Red line: no fabricated search-volume number anywhere on the surface.
  const body = await page.locator("main").textContent();
  expect(body).not.toContain("search volume");
});

