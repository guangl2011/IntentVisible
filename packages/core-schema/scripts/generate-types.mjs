// Regenerates src/generated/*.ts from schemas/*.schema.json. The TypeScript
// contract types are a build artifact of the JSON Schema files — never edit
// them by hand.
//
// Usage:
//   node scripts/generate-types.mjs           # write src/generated
//   node scripts/generate-types.mjs --check   # exit 1 when committed files are stale
//
// Run via: corepack pnpm --filter @intentvisible/core-schema generate

import { execFileSync } from "node:child_process";
import { existsSync } from "node:fs";
import { compile } from "json-schema-to-typescript";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const pkgRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(pkgRoot, "../..");
const schemasDir = path.join(pkgRoot, "schemas");
const outDir = path.join(pkgRoot, "src", "generated");

// Generated files are committed, so the generator's output must be stable
// under the repo's Prettier config: format everything we emit, in both
// write and --check modes, or the CI staleness check drifts on formatting.
const prettierBin = path.join(repoRoot, "node_modules", ".bin", "prettier");

function prettify(content, filePath) {
  const bin = existsSync(prettierBin) ? prettierBin : "prettier";
  return execFileSync(bin, ["--stdin-filepath", filePath], { input: content }).toString();
}

const BANNER = [
  "/**",
  " * Generated by scripts/generate-types.mjs from schemas/*.schema.json — do not edit by hand.",
  " * Regenerate with: corepack pnpm --filter @intentvisible/core-schema generate",
  " */",
].join("\n");

// One entry per published schema. reExports names the types each generated
// module contributes to generated/index.ts; shared defs (SnapshotRef, Price)
// are exported exactly once across the index.
const ENTITIES = [
  {
    schema: "intent-record.schema.json",
    typeName: "IntentRecord",
    outFile: "intent-record.ts",
    reExports: ["IntentRecord"],
  },
  {
    schema: "brand-profile.schema.json",
    typeName: "BrandProfile",
    outFile: "brand-profile.ts",
    reExports: ["BrandProfile", "SnapshotRef"],
  },
  {
    schema: "product-profile.schema.json",
    typeName: "ProductProfile",
    outFile: "product-profile.ts",
    reExports: ["ProductProfile", "Price", "SpecificationEntry", "FaqEntry", "SkuSummary"],
  },
  {
    schema: "sku-intent-mapping.schema.json",
    typeName: "SkuIntentMapping",
    outFile: "sku-intent-mapping.ts",
    reExports: ["SkuIntentMapping"],
  },
];

const STYLE = {
  semi: true,
  singleQuote: false,
  printWidth: 100,
  tabWidth: 2,
  trailingComma: "all",
};

async function render(entity) {
  const schema = JSON.parse(await readFile(path.join(schemasDir, entity.schema), "utf8"));
  const compiled = await compile(schema, entity.typeName, {
    bannerComment: "",
    style: STYLE,
    // Records arrive as plain arrays that must satisfy min/maxItems at
    // validation time; emit unbounded array types, not tuples.
    ignoreMinAndMaxItems: true,
  });
  const moduleSpecifier = `./${entity.outFile.replace(/\.ts$/, ".js")}`;
  const content = prettify(`${BANNER}\n\n${compiled.trimEnd()}\n`, entity.outFile);
  return { ...entity, moduleSpecifier, content };
}

async function build() {
  const rendered = await Promise.all(ENTITIES.map(render));
  const indexLines = [
    BANNER,
    "",
    ...rendered.map(
      (r) => `export type { ${r.reExports.join(", ")} } from "${r.moduleSpecifier}";`,
    ),
    "",
  ].join("\n");
  return { rendered, index: prettify(indexLines, "generated-index.ts") };
}

const check = process.argv.includes("--check");
const { rendered, index } = await build();

if (check) {
  const stale = [];
  for (const r of rendered) {
    const existing = await readFile(path.join(outDir, r.outFile), "utf8").catch(() => null);
    if (existing !== r.content) {
      stale.push(`src/generated/${r.outFile}`);
    }
  }
  const existingIndex = await readFile(path.join(outDir, "index.ts"), "utf8").catch(() => null);
  if (existingIndex !== index) {
    stale.push("src/generated/index.ts");
  }
  if (stale.length > 0) {
    console.error(
      `Generated types are stale: ${stale.join(", ")}. Run: corepack pnpm --filter @intentvisible/core-schema generate`,
    );
    process.exit(1);
  }
  console.log("Generated types are up to date.");
} else {
  await mkdir(outDir, { recursive: true });
  for (const r of rendered) {
    await writeFile(path.join(outDir, r.outFile), r.content);
  }
  await writeFile(path.join(outDir, "index.ts"), index);
  console.log(`Wrote ${rendered.length} generated modules + index.ts to src/generated`);
}
